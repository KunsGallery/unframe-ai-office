const n = day => { let h = 0; for (const c of day) h = (h * 31 + c.charCodeAt(0)) >>> 0; return h; };
/** day: 'YYYY-MM-DD' → { kind: 'line', text, by } | { kind: 'quiz', q, a } */
export function dailyLine(day) {
  const h = n(day), d = +day.slice(8);
  if (d % 2 === 0) { const [q, a] = QUIZ[h % QUIZ.length]; return { kind: 'quiz', q, a }; }
  const [text, by] = LINES[h % LINES.length];
  return { kind: 'line', text, by };
}
